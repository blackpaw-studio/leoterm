#!/usr/bin/env swift
// Generates Packages/LeoKit/Sources/LeoKit/Appearance/LeoEmojiCatalog+Data.swift,
// the agent-appearance picker's emoji, from two pinned Unicode files:
//
//   curl -sSfLO https://unicode.org/Public/emoji/15.1/emoji-test.txt
//   curl -sSfLO https://raw.githubusercontent.com/unicode-org/cldr/release-44/common/annotations/en.xml
//   swift scripts/gen-emoji-catalog.swift emoji-test.txt en.xml \
//       Packages/LeoKit/Sources/LeoKit/Appearance/LeoEmojiCatalog+Data.swift
//
// Emoji 15.1 renders on macOS 14.4+ / iOS 17.4+. Bumping the pin means new
// URLs, new hashes below, and a regenerate; the tests pin the entry count.
//
// Only fully-qualified entries are kept (components and unqualified forms are
// not), in CLDR order. Names come from emoji-test.txt, keywords from CLDR's
// English annotations; a skin-toned or otherwise modified emoji with no
// annotation of its own takes its base emoji's keywords.

import CryptoKit
import Foundation

let unicodeVersion = "15.1"
let pinnedHashes = [
    "emoji-test.txt": "d876ee249aa28eaa76cfa6dfaa702847a8d13b062aa488d465d0395ee8137ed9",
    "en.xml": "13db8bb0a85a1ab9c46dd70f6170d72e7938063eb04cb2ee65e46d0378cfebf6",
]

func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data("gen-emoji-catalog: \(message)\n".utf8))
    exit(1)
}

func readPinned(_ path: String, as name: String) -> String {
    guard let data = FileManager.default.contents(atPath: path) else { fail("cannot read \(path)") }
    let hash = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    guard hash == pinnedHashes[name] else { fail("\(path) is not the pinned \(name) (sha256 \(hash))") }
    return String(decoding: data, as: UTF8.self)
}

/// CLDR `<annotation cp="…">a | b</annotation>` keywords by emoji (tts
/// names are skipped: emoji-test.txt already names each emoji).
func keywords(fromCLDR xml: String) -> [String: [String]] {
    let pattern = try! NSRegularExpression(pattern: #"<annotation cp="([^"]+)">([^<]*)</annotation>"#)
    let range = NSRange(xml.startIndex..., in: xml)
    var out: [String: [String]] = [:]
    for match in pattern.matches(in: xml, range: range) {
        guard let cp = Range(match.range(at: 1), in: xml), let words = Range(match.range(at: 2), in: xml) else { continue }
        out[unescape(String(xml[cp]))] = unescape(String(xml[words])).components(separatedBy: " | ").map {
            $0.trimmingCharacters(in: .whitespaces)
        }
    }
    return out
}

func unescape(_ text: String) -> String {
    [("&lt;", "<"), ("&gt;", ">"), ("&quot;", "\""), ("&apos;", "'"), ("&amp;", "&")].reduce(text) {
        $0.replacingOccurrences(of: $1.0, with: $1.1)
    }
}

/// The emoji with variation selectors and skin-tone modifiers removed,
/// for borrowing a base emoji's keywords.
func base(_ emoji: String) -> String {
    String(String.UnicodeScalarView(emoji.unicodeScalars.filter { $0.value != 0xFE0F && !(0x1F3FB...0x1F3FF).contains($0.value) }))
}

func clean(_ field: String) -> String {
    field.replacingOccurrences(of: "\t", with: " ").replacingOccurrences(of: "\n", with: " ")
}

let arguments = CommandLine.arguments
guard arguments.count == 4 else { fail("usage: gen-emoji-catalog.swift <emoji-test.txt> <en.xml> <output.swift>") }
let test = readPinned(arguments[1], as: "emoji-test.txt")
let cldr = keywords(fromCLDR: readPinned(arguments[2], as: "en.xml"))

var lines: [String] = []
var count = 0
for line in test.split(separator: "\n", omittingEmptySubsequences: false) {
    if line.hasPrefix("# group: ") {
        let group = line.dropFirst("# group: ".count).trimmingCharacters(in: .whitespaces)
        if group != "Component" { lines.append("G\t\(clean(group))") }
        continue
    }
    guard !line.hasPrefix("#"), line.contains("; fully-qualified") else { continue }
    // `1F600 ; fully-qualified # 😀 E1.0 grinning face`
    guard let hash = line.range(of: "# ") else { fail("unparsed line: \(line)") }
    let parts = line[hash.upperBound...].split(separator: " ", maxSplits: 2).map(String.init)
    guard parts.count == 3, parts[1].hasPrefix("E") else { fail("unparsed line: \(line)") }
    let emoji = parts[0]
    let name = parts[2]
    let words = cldr[emoji] ?? cldr[base(emoji)] ?? cldr[emoji.replacingOccurrences(of: "\u{FE0F}", with: "")] ?? []
    let keywords = words.filter { $0 != name }.map(clean)
    let isModified = emoji.unicodeScalars.contains { (0x1F3FB...0x1F3FF).contains($0.value) }
    lines.append([isModified ? "T" : "E", emoji, clean(name), keywords.joined(separator: "|")].joined(separator: "\t"))
    count += 1
}

let body = lines.joined(separator: "\n")
guard !body.contains("\"\"\"#") else { fail("data would close the raw string literal") }
let source = """
// Generated by scripts/gen-emoji-catalog.swift from Unicode emoji-test.txt
// \(unicodeVersion) and CLDR release-44 annotations/en.xml. Do not edit.
// \(count) fully-qualified emoji. One line each: `E` (or `T` for a
// skin-toned variant), the emoji, its name, its keywords joined by `|`;
// a `G` line starts a group.

extension LeoEmojiCatalog {
    static let generatedUnicodeVersion = "\(unicodeVersion)"

    static let generatedData = #\"\"\"
\(body)
\"\"\"#
}

"""
do {
    try source.write(toFile: arguments[3], atomically: true, encoding: .utf8)
} catch {
    fail("cannot write \(arguments[3]): \(error)")
}
print("wrote \(count) emoji to \(arguments[3])")
