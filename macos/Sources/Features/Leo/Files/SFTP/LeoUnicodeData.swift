        0620 0626 0628 062A-062E 0633-063F 0641-0647 0649-064A 066E-066F 0678-0687 069A-06BF 06C1-06C2 06CC 06CE
        06D0-06D1 06FA-06FC 06FF 0750-0758 075C-076A 076D-0770 0772 0775-0777 077A-077F 0886 0889-088D 088F 08A0-08A9
        08AF-08B0 08B3-08B8 08BA-08C8
        """)

    /// Arabic-script letters that join to the letter before them
    /// (Joining_Type D or R), from the same file and blocks.
    static let joinsBackward = parseRanges("""
        0620 0622-063F 0641-064A 066E-066F 0671-0673 0675-06D3 06D5 06EE-06EF 06FA-06FC 06FF 0750-077F 0870-0882 0886
        0889-088F 08A0-08AC 08AE-08C8
        """)

    /// One sequence per line, scalars as space-separated hex.
    private static func parseSequences(_ text: String) -> [[Unicode.Scalar]] {
        text.split(separator: "\n").map { line in
            line.split(separator: " ").compactMap { UInt32($0, radix: 16).flatMap(Unicode.Scalar.init) }
        }
    }

    /// Space-separated hex scalars and "first-last" ranges.
    private static func parseRanges(_ text: String) -> Set<UInt32> {
        Set(text.split(whereSeparator: \.isWhitespace).flatMap { item -> ClosedRange<UInt32> in
            let bounds = item.split(separator: "-").compactMap { UInt32($0, radix: 16) }
            return bounds[0]...bounds[bounds.count - 1]
        })
    }
